            s_lut[992] = 18'sd10012; s_lut[993] = 18'sd10009; s_lut[994] = 18'sd10005; s_lut[995] = 18'sd10002; s_lut[996] = 18'sd9999; s_lut[997] = 18'sd9995; s_lut[998] = 18'sd9992; s_lut[999] = 18'sd9988;
            s_lut[1000] = 18'sd9985; s_lut[1001] = 18'sd9981; s_lut[1002] = 18'sd9978; s_lut[1003] = 18'sd9975; s_lut[1004] = 18'sd9971; s_lut[1005] = 18'sd9968; s_lut[1006] = 18'sd9964; s_lut[1007] = 18'sd9961;
            s_lut[1008] = 18'sd9957; s_lut[1009] = 18'sd9954; s_lut[1010] = 18'sd9951; s_lut[1011] = 18'sd9947; s_lut[1012] = 18'sd9944; s_lut[1013] = 18'sd9940; s_lut[1014] = 18'sd9937; s_lut[1015] = 18'sd9933;
            s_lut[1016] = 18'sd9930; s_lut[1017] = 18'sd9926; s_lut[1018] = 18'sd9923; s_lut[1019] = 18'sd9919; s_lut[1020] = 18'sd9916; s_lut[1021] = 18'sd9913; s_lut[1022] = 18'sd9909; s_lut[1023] = 18'sd9906;
    end

    
    always @(posedge clk) begin
        if (lut_we) s_lut[lut_addr] <= lut_wdata;
    end

    // ---------------------------------------------------------------
    // 级 1：dx = u - cx, dy = v - cy   （Q4.12）
    // ---------------------------------------------------------------
    reg signed [23:0] dx_s1, dy_s1;
    reg               v_s1;
    
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            dx_s1 <= 24'sd0; dy_s1 <= 24'sd0; v_s1 <= 1'b0;
        end else begin
            dx_s1 <= $signed({u, 12'b0}) - cx_q;
            dy_s1 <= $signed({v, 12'b0}) - cy_q;
            v_s1  <= in_valid;
        end
    end

    // ---------------------------------------------------------------
    // 级 2：dx2, dy2, dxy, r2（Q4.12 的像素平方）
    //   24bit*24bit -> 48bit(Q8.24)，>>12 回到 Q4.12
    //   dx^2 最大 1.57e9、r^2 最大 5.32e9 —— 34bit 才装得下（32bit 会溢出）
    // ---------------------------------------------------------------
    
    localparam integer P2W = PW + 1;   // r2 + 2*dx2：最大 1.34e10 -> 35bit
    
    localparam integer MW  = 72;       // Q.30 x Q4.12 = Q4.42，且还要 <<1

    reg  signed [PW-1:0]  dx2_s2, dy2_s2, dxy_s2, r2_s2;
    reg  signed [23:0]    dx_s2, dy_s2;
    reg                   v_s2;

    wire signed [47:0]    dx2_f = dx_s1 * dx_s1;      // Q8.24
    wire signed [47:0]    dy2_f = dy_s1 * dy_s1;      // Q8.24
    wire signed [47:0]    dxy_f = dx_s1 * dy_s1;      // Q8.24
    // 在 48bit 上下文里右移（不截断），再显式取低位
    wire signed [47:0]    dx2_sh = dx2_f >>> 12;      // Q4.12，最大 4.03e9
    wire signed [47:0]    dy2_sh = dy2_f >>> 12;
    wire signed [47:0]    dxy_sh = dxy_f >>> 12;      // Q4.12，最大 2.28e9
    wire signed [PW-1:0]  dx2_s2_n = dx2_sh[PW-1:0];
    wire signed [PW-1:0]  dy2_s2_n = dy2_sh[PW-1:0];

    
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            dx2_s2 <= 0; dy2_s2 <= 0; dxy_s2 <= 0; r2_s2 <= 0;
            dx_s2 <= 0; dy_s2 <= 0; v_s2 <= 1'b0;
        end else begin
            dx2_s2 <= dx2_s2_n;
            dy2_s2 <= dy2_s2_n;
            dxy_s2 <= dxy_sh[PW-1:0];
            r2_s2  <= dx2_s2_n + dy2_s2_n;    // 34bit 加法，最大 5.32e9 < 2^33
            dx_s2  <= dx_s1;
            dy_s2  <= dy_s1;
            v_s2   <= v_s1;
        end
    end

    // ---------------------------------------------------------------
    // 级 3：LUT 读地址
    //   表按 r^2 步进 2048 生成：index = r^2 / 2048 = r2_s2 >> 23
    //   1080p 最大 index = 633（10bit 地址 0..1023 够用）
    // ---------------------------------------------------------------
    reg signed [17:0] s_s3;
    reg signed [23:0] dx_s3, dy_s3;
    reg signed [PW-1:0] dx2_s3, dy2_s3, dxy_s3, r2_s3;
    reg               v_s3;
    // r2+2*dx2 / r2+2*dy2 提前在这一级算好并寄存。
    // 否则它们会与 32x35 乘法器挤在级 4a 的同一拍里，148.5MHz 下仍差 1.24~1.40 ns。
    reg signed [P2W-1:0] r2_2dx2_s3, r2_2dy2_s3;
    wire [AW-1:0] raddr = r2_s2[AW+22:23];   // = r^2/2048，不是 [31:22]（那是 r^2/1024）
    
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            s_s3 <= 18'sd16384;
            dx_s3 <= 0; dy_s3 <= 0; dx2_s3 <= 0; dy2_s3 <= 0; dxy_s3 <= 0; r2_s3 <= 0;
            r2_2dx2_s3 <= 0; r2_2dy2_s3 <= 0;
            v_s3 <= 1'b0;
        end else begin
            s_s3   <= s_lut[raddr];
            dx_s3  <= dx_s2;  dy_s3  <= dy_s2;
            dx2_s3 <= dx2_s2; dy2_s3 <= dy2_s2; dxy_s3 <= dxy_s2;
            r2_s3  <= r2_s2;
            // 提前一级算好，给级 4a 的乘法器腾出一整拍
            r2_2dx2_s3 <= r2_s2 + dx2_s2 + dx2_s2;
            r2_2dy2_s3 <= r2_s2 + dy2_s2 + dy2_s2;
            v_s3   <= v_s2;
        end
    end

    // ---------------------------------------------------------------
    // 级 4：切向项（Q4.12）
    //   tx = (2*P1*dxy + P2*(r2 + 2*dx2)) >> 30
    //   ty = (P1*(r2 + 2*dy2) + 2*P2*dxy) >> 30
    //   P.Q.30 x Q4.12 -> Q4.42，32x35 位乘积需要 67bit，再用 72bit 容器
    // ---------------------------------------------------------------
    // ---- 级 4a：只做乘法，结果寄存 ----
    // 原来"35 位加法链 + 32x35 乘法 + 累加 + 移位"全挤在一级里，
    // 148.5MHz(6.727ns) 下实测 WNS = -2.152 ns（路径 15 级逻辑），
    // ty_s4 出错会让行包络的 ymax 估计失效、预取目标跑偏。
    // 拆成两级：4a 只乘，4b 只累加+移位。
    reg signed [MW-1:0] tx_a_r, tx_b_r, ty_a_r, ty_b_r;
    reg signed [23:0]   dx_s4a, dy_s4a;
    reg signed [17:0]   s_s4a;
    reg                 v_s4a;

    // r2_2dx2 / r2_2dy2 已在级 3 寄存（见上），这里直接用

    
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            tx_a_r <= 0; tx_b_r <= 0; ty_a_r <= 0; ty_b_r <= 0;
            dx_s4a <= 0; dy_s4a <= 0; s_s4a <= 18'sd16384; v_s4a <= 1'b0;
        end else begin
            tx_a_r <= (p1q * dxy_s3) <<< 1;
            tx_b_r <= p2q * r2_2dx2_s3;
            ty_a_r <= p1q * r2_2dy2_s3;
            ty_b_r <= (p2q * dxy_s3) <<< 1;
            dx_s4a <= dx_s3; dy_s4a <= dy_s3;
            s_s4a  <= s_s3;  v_s4a  <= v_s3;
        end
    end

    // ---- 级 4b：累加 + 移位 ----
    reg signed [23:0] tx_s4, ty_s4;
    reg signed [23:0] dx_s4, dy_s4;
    reg signed [17:0] s_s4;
    reg               v_s4;

    wire signed [MW-1:0] tx_sh = (tx_a_r + tx_b_r) >>> 30;
    wire signed [MW-1:0] ty_sh = (ty_a_r + ty_b_r) >>> 30;

    
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            tx_s4 <= 0; ty_s4 <= 0; dx_s4 <= 0; dy_s4 <= 0;
            s_s4 <= 18'sd16384; v_s4 <= 1'b0;
        end else begin
            tx_s4 <= tx_sh[23:0];
            ty_s4 <= ty_sh[23:0];
            dx_s4 <= dx_s4a; dy_s4 <= dy_s4a;
            s_s4  <= s_s4a;  v_s4  <= v_s4a;
        end
    end

    // ---------------------------------------------------------------
    // 级 5：径向缩放
    //   xs = dx*s + tx ;  ys = dy*s + ty   （最后加回主点得到绝对源坐标）
    //   dx(24bit) x s(18bit) -> Q6.26，42bit 容器够（最大约 2^36）
    // ---------------------------------------------------------------
    reg signed [23:0] xs_s5, ys_s5;
    reg               v_s5;
    wire signed [41:0] xr_f = dx_s4 * s_s4;
    wire signed [41:0] yr_f = dy_s4 * s_s4;
    wire signed [41:0] xr_sh = xr_f >>> 14;      // 42bit 上下文，先移位后截断
    wire signed [41:0] yr_sh = yr_f >>> 14;
    wire signed [41:0] xs_sum = xr_sh + tx_s4 + cx_q;
    wire signed [41:0] ys_sum = yr_sh + ty_s4 + cy_q;
    
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            xs_s5 <= 0; ys_s5 <= 0; v_s5 <= 1'b0;
        end else begin
            // 输出必须是绝对源坐标，要把主点加回去（之前漏了，导致只有右下角有效）
            xs_s5 <= xs_sum[23:0];
            ys_s5 <= ys_sum[23:0];
            v_s5  <= v_s4;
        end
    end

    // ---------------------------------------------------------------
    // 级 6：输出寄存器
    // ---------------------------------------------------------------
    
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            xs_q <= 0; ys_q <= 0; out_valid <= 1'b0;
        end else begin
            xs_q      <= xs_s5;
            ys_q      <= ys_s5;
            out_valid <= v_s5;
        end
    end

endmodule

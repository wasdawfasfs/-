    reg signed[17:0] next_s3;
    reg[15:0] brown_frac_s3;
    reg signed[35:0] interp_product_s4a;
    wire signed[18:0] table_delta=$signed({next_s3[17],next_s3})-$signed({s_s3[17],s_s3});
    wire signed[16:0] table_fraction=$signed({1'b0,brown_frac_s3});
    wire signed[35:0] table_correction=(interp_product_s4a+36'sd32768)>>>16;
    reg signed [23:0] dx_s3, dy_s3;
    reg signed [PW-1:0] dx2_s3, dy2_s3, dxy_s3, r2_s3;
    reg               v_s3;
    // r2+2*dx2 / r2+2*dy2 提前在这一级算好并寄存。
    // 否则它们会与 32x35 乘法器挤在级 4a 的同一拍里，148.5MHz 下仍差 1.24~1.40 ns。
    reg signed [P2W-1:0] r2_2dx2_s3, r2_2dy2_s3;
    wire[PW-1:0] brown_index=r2_s2>>24;
    wire [AW-1:0] raddr = full_view ? ((brown_index>((1<<AW)-1))?{AW{1'b1}}:brown_index[AW-1:0]) : ((|r2_s2[PW-1:AW+23]) ? {AW{1'b1}} : r2_s2[AW+22:23]);   // = r^2/2048，不是 [31:22]（那是 r^2/1024）

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            s_s3 <= 18'sd16384;
            dx_s3 <= 0; dy_s3 <= 0; dx2_s3 <= 0; dy2_s3 <= 0; dxy_s3 <= 0; r2_s3 <= 0;
            r2_2dx2_s3 <= 0; r2_2dy2_s3 <= 0;
            v_s3 <= 1'b0;
        end else begin
            s_s3 <= full_view?brown_lut[raddr]:s_lut[raddr];
            next_s3 <= brown_lut[{1'b0,raddr}+1'b1];brown_frac_s3<=r2_s2[23:8];
            dx_s3  <= dx_s2;  dy_s3  <= dy_s2;
            dx2_s3 <= dx2_s2; dy2_s3 <= dy2_s2; dxy_s3 <= dxy_s2;
            r2_s3  <= r2_s2;
            // 提前一级算好，给级 4a 的乘法器腾出一整拍
            r2_2dx2_s3 <= r2_s2 + dx2_s2 + dx2_s2;
            r2_2dy2_s3 <= r2_s2 + dy2_s2 + dy2_s2;
            v_s3   <= v_s2;
        end

// 旧 Brown 镜头的 Q12 坐标映射，保留原有模式兼容；不得与 rational 表混用。
//=============================================================================
// dist_calc.v : 二阶径向 + 切向畸变 逆映射引擎（任务2 核心）
//
// 数学
// ---------------------------------------------------------------------------
// 相机畸变（正向，Brown-Conrady）：
//   x_u = x_d*(1 + k1*rd^2 + k2*rd^4) + 2*p1*x_d*y_d + p2*(rd^2 + 2*x_d^2)
//   y_u = y_d*(1 + k1*rd^2 + k2*rd^4) + p1*(rd^2 + 2*y_d^2) + 2*p2*x_d*y_d
// 其中 (x_u,y_u) 为理想(无畸变)归一化坐标，(x_d,y_d) 为实际(畸变)坐标。
//
// 做「畸变校正」需要的是逆向映射：对输出图像每个理想像素 (u,v)，
// 求出它在原始畸变图中的源坐标 (x_d,y_d)，然后去采样该位置的像素。
//
//   径向(逆向)  : x_d_rad = x_u * s(r_u^2)
//                 其中 s(r^2) = 1 + k1*r^2/f^2 + k2*r^4/f^4   （r 以像素为单位，
//                 f 为焦距像素数；k1,k2 已吸收 1/f^2、1/f^4 的缩放）
//   切向(逆向)  : 对切向项取负号做一阶补偿（对小畸变足够精确，误差 O(k^2)）
//                 tx = 2*P1*x_u*y_u + P2*(r_u^2 + 2*x_u^2)
//                 ty = P1*(r_u^2 + 2*y_u^2) + 2*P2*x_u*y_u
//   x_d = x_u * s + tx ;  y_d = y_u * s + ty
//
// 为什么用 LUT 做径向
// ---------------------------------------------------------------------------
// s(r^2) 是单变量平滑函数，用一个 1024 项的 BRAM 存（Q2.14 定点），
// 既省掉高精度乘加链，又避免了归一化/反归一化的除法。
// 表内容由标定结果（k1,k2,f）离线算好后写入，可通过 UART 在线更新。
//
// 定点格式与位宽
// ---------------------------------------------------------------------------
//   dx,dy,tx,ty,xs,ys                : Q4.12（有符号，像素×4096）
//   dx2,dy2,dxy,r2                   : Q4.12（有符号，像素^2 × 4096）
//   s                                : Q2.14（纯比例因子，1.0 = 16384）
//   P1s,P2s                          : Q.30（有符号 32 位，值 = p/f）
//     注意是 p/f 而不是 p/f^2：前向模型在像素域是
//       tx = (2*p1*dx*dy + p2*(r^2+2dx^2)) / f
//     所以系数必须除以 f 的一次方。用 p/f^2 时 p1q 会小到 Q.30 只能存 0。
//   cx_q,cy_q                        : Q4.12（主点，像素×4096）
//
// 位宽（1080p，cx=927.40、cy=517.96 时必须逐项核对，这里都留了余量）
// ---------------------------------------------------------------------------
//   |dx| <= 991.6 px                     -> dx        23bit+符号 = 24bit
//   dx^2 <= 9.83e5 px^2, Q4.12 = 4.03e9 -> dx2       32bit 无符号 / 33bit 有符号
//   r^2  <= 1.30e6 px^2, Q4.12 = 5.32e9 -> r2        33bit 无符号 / 34bit 有符号
//   r^2+2dx^2 <= 3.27e6 px^2 = 1.34e10  -> 2*dx2+r2  34bit 无符号 / 35bit 有符号
//   LUT 索引 = r^2/2048（表按 r^2 步进 2048 生成）<= 633 -> 10bit 够用
//
//   ！！32bit 有符号只到 2.15e9，即 r^2 <= 524288 px^2（r <= 724 px），1080p
//   画面一大半半径都超了，所以 r2/dx2/dy2/dxy 绝不能是 32bit。
//
// 关于 Verilog 表达式位宽
// ---------------------------------------------------------------------------
//   赋值语句的 RHS 会按上下文宽度求值：`reg [31:0] x = big48 >>> 12;` 会先把
//   big48 截成 32bit 再移位（丢掉高 16bit），而不是先移位再截断。所有跨位宽的
//   乘/移位这里都拆成「显式宽度的中间 wire + 显式 part-select」，不依赖工具对
//   上下文宽度的解释。
//
// 流水线：6 级，输入到输出固定延迟 6 拍（valid 同步打拍）
//=============================================================================


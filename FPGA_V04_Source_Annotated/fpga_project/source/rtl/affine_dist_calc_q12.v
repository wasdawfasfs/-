    // 级 4：切向项（Q4.12）
    //   tx = (2*P1*dxy + P2*(r2 + 2*dx2)) >> 30
    //   ty = (P1*(r2 + 2*dy2) + 2*P2*dxy) >> 30
    //   P.Q.30 x Q4.12 -> Q4.42，32x35 位乘积需要 67bit，再用 72bit 容器
    // ---------------------------------------------------------------
    // ---- 级 4a：只做乘法，结果寄存 ----
    // 原来"35 位加法链 + 32x35 乘法 + 累加 + 移位"全挤在一级里，
    // 148.5MHz(6.727ns) 下实测 WNS = -2.152 ns（路径 15 级逻辑），
    // ty_s4 出错会让行包络的 ymax 估计失效、预取目标跑偏。
    // 拆成两级：4a 只乘，4b 只累加+移位。
    reg signed [MW-1:0] tx_a_r, tx_b_r, ty_a_r, ty_b_r;
    reg signed [23:0]   dx_s4a, dy_s4a;
    reg signed [17:0]   s_s4a;
    reg                 v_s4a;

    // r2_2dx2 / r2_2dy2 已在级 3 寄存（见上），这里直接用


    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            tx_a_r <= 0; tx_b_r <= 0; ty_a_r <= 0; ty_b_r <= 0;
            dx_s4a <= 0; dy_s4a <= 0; s_s4a <= 18'sd16384; v_s4a <= 1'b0;
        end else begin
            tx_a_r <= (p1q * dxy_s3) <<< 1;
            tx_b_r <= p2q * r2_2dx2_s3;
            ty_a_r <= p1q * r2_2dy2_s3;
            ty_b_r <= (p2q * dxy_s3) <<< 1;
            dx_s4a <= dx_s3; dy_s4a <= dy_s3;
            s_s4a <= s_s3; interp_product_s4a<=table_delta*table_fraction; v_s4a<=v_s3;
        end
    end

    // ---- 级 4b：累加 + 移位 ----
    reg signed [23:0] tx_s4, ty_s4;
    reg signed [23:0] dx_s4, dy_s4;
    reg signed [17:0] s_s4;
    reg               v_s4;

    wire signed [MW-1:0] tx_sh = (tx_a_r + tx_b_r) >>> 30;
    wire signed [MW-1:0] ty_sh = (ty_a_r + ty_b_r) >>> 30;


    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            tx_s4 <= 0; ty_s4 <= 0; dx_s4 <= 0; dy_s4 <= 0;
            s_s4 <= 18'sd16384; v_s4 <= 1'b0;
        end else begin
            tx_s4 <= tx_sh[23:0];
            ty_s4 <= ty_sh[23:0];
            dx_s4 <= dx_s4a; dy_s4 <= dy_s4a;
            s_s4 <= full_view?($signed(s_s4a)+table_correction):s_s4a; v_s4<=v_s4a;
        end
    end

    // ---------------------------------------------------------------
    // 级 5：径向缩放
    //   xs = dx*s + tx ;  ys = dy*s + ty   （最后加回主点得到绝对源坐标）
    //   dx(24bit) x s(18bit) -> Q6.26，42bit 容器够（最大约 2^36）
    // ---------------------------------------------------------------
    reg signed [23:0] xs_s5, ys_s5;
    reg               v_s5;
    wire signed [41:0] xr_f = dx_s4 * s_s4;
    wire signed [41:0] yr_f = dy_s4 * s_s4;
    reg signed [41:0] xr_reg,yr_reg;
    reg signed [23:0] tx_reg,ty_reg,cx_reg,cy_reg;
    
    reg radial_valid;

    always @(posedge clk or negedge rst_n) begin
      if(!rst_n) begin xr_reg<=0;yr_reg<=0;tx_reg<=0;ty_reg<=0;cx_reg<=0;cy_reg<=0;radial_valid<=0;end
      else begin xr_reg<=xr_f;yr_reg<=yr_f;tx_reg<=tx_s4;ty_reg<=ty_s4;cx_reg<=cx_q;cy_reg<=cy_q;radial_valid<=v_s4;end
    end
    wire signed [41:0] xr_sh = xr_reg >>> 14;      // 42bit 上下文，先移位后截断
    wire signed [41:0] yr_sh = yr_reg >>> 14;
    wire signed [41:0] xs_sum = xr_sh + tx_reg + cx_reg;
    wire signed [41:0] ys_sum = yr_sh + ty_reg + cy_reg;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            xs_s5 <= 0; ys_s5 <= 0; v_s5 <= 1'b0;
        end else begin
            // 输出必须是绝对源坐标，要把主点加回去（之前漏了，导致只有右下角有效）
            xs_s5 <= xs_sum[23:0];
            ys_s5 <= ys_sum[23:0];
            v_s5  <= radial_valid;
        end
    end

    // ---------------------------------------------------------------
    // 级 6：输出寄存器
    // ---------------------------------------------------------------

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            xs_q <= 0; ys_q <= 0; out_valid <= 1'b0;
        end else begin
            xs_q      <= xs_s5;
            ys_q      <= ys_s5;
            out_valid <= v_s5;
        end
    end


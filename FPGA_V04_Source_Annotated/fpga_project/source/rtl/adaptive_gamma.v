    diagnostic<={sum,count,center,low_y,high_y};sum<=0;count<=0;low_y<=255;high_y<=0;center<=0;
   end
  end
 end
endmodule

// 保存全部相关诊断载荷，直至接收方应答。

module preproc_snapshot_cdc(input src_clk,src_rst_n,input[127:0] payload,input[7:0] frame_id,
 input dst_clk,dst_rst_n,output reg[127:0] snapshot);
 reg[127:0] held;reg[7:0] seen;reg req,ack,ack1,ack2,req1,req2;
 
 always @(posedge src_clk or negedge src_rst_n)begin
  if(!src_rst_n)begin held<=0;seen<=0;req<=0;ack1<=0;ack2<=0;end
  else begin ack1<=ack;ack2<=ack1;
   if(frame_id!=seen&&req==ack2)begin held<=payload;seen<=frame_id;req<=~req;end
  end
 end
 
 always @(posedge dst_clk or negedge dst_rst_n)begin
  if(!dst_rst_n)begin req1<=0;req2<=0;ack<=0;snapshot<=0;end
  else begin req1<=req;req2<=req1;if(req2!=ack)begin snapshot<=held;ack<=req2;end end
 end
endmodule
